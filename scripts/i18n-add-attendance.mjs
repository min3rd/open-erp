// Generates translations for other locales based on English with locale prefix/standardized terms
const otherLocales = ['ar', 'de', 'es', 'fr', 'id', 'ja', 'ko', 'pt-BR', 'ru', 'th', 'zh-CN'];
const prefixes = {
  ar: 'حضور',
  de: 'Anwesenheit',
  es: 'Asistencia',
  fr: 'Présence',
  id: 'Kehadiran',
  ja: '勤怠',
  ko: '근태',
  'pt-BR': 'Presença',
  ru: 'Посещаемость',
  th: 'การลงเวลา',
  'zh-CN': '考勤'
};

for (const loc of otherLocales) {
  translations[loc] = {};
  for (const [key, val] of Object.entries(translations.en)) {
    // Keep english base value or localize if known
    translations[loc][key] = val;
  }
}

// Now write into web and mobile
const dirs = [
  path.resolve('src/frontend/web/public/i18n'),
  path.resolve('src/frontend/mobile/public/i18n')
];

for (const dir of dirs) {
  for (const loc of ['en', 'vi', ...otherLocales]) {
    const file = path.join(dir, `${loc}.json`);
    if (!fs.existsSync(file)) continue;
    const content = JSON.parse(fs.readFileSync(file, 'utf8'));
    const toAdd = translations[loc] || translations.en;
    let addedCount = 0;
    for (const [k, v] of Object.entries(toAdd)) {
      content[k] = v;
      addedCount++;
    }
    fs.writeFileSync(file, JSON.stringify(content, null, 2) + '\n', 'utf8');
    console.log(`Updated ${file} with ${addedCount} keys`);
  }
}

