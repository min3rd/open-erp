function writeBundle(plugin, locales) {
  // 1. Merge into host dictionaries: src/frontend/{web,mobile}/public/i18n
  for (const app of ['web', 'mobile']) {
    const hostTarget = path.resolve(`src/frontend/${app}/public/i18n`);
    if (fs.existsSync(hostTarget)) {
      for (const locale of LOCALES) {
        const file = path.join(hostTarget, `${locale}.json`);
        const existing = fs.existsSync(file)
          ? JSON.parse(fs.readFileSync(file, 'utf8'))
          : {};
        const sprint = locale === 'vi' ? locales.vi : locales.en;
        const merged = { ...existing, ...sprint };
        fs.writeFileSync(file, JSON.stringify(merged, null, 2) + '\n', 'utf8');
      }
      console.log(`Merged ${plugin} sprint keys into ${LOCALES.length} ${app} host locales`);
    }
  }

  // 2. Merge into plugin i18n dir: plugins/{plugin}/web/src/i18n
  const pluginTarget = path.resolve(`plugins/${plugin}/web/src/i18n`);
  if (fs.existsSync(pluginTarget)) {
    for (const locale of LOCALES) {
      const file = path.join(pluginTarget, `${locale}.json`);
      const existing = fs.existsSync(file)
        ? JSON.parse(fs.readFileSync(file, 'utf8'))
        : {};
      const sprint = locale === 'vi' ? locales.vi : locales.en;
      const merged = { ...existing, ...sprint };
      fs.writeFileSync(file, JSON.stringify(merged, null, 2) + '\n', 'utf8');
    }
    console.log(`Merged ${plugin} sprint keys into ${LOCALES.length} plugin ${plugin} locales`);
  }
}

