const targets = [
  'src/frontend/web/public/i18n',
  'src/frontend/mobile/public/i18n',
  'plugins/attendance/src/main/resources/META-INF/resources/i18n',
];

for (const dir of targets) {
  if (!fs.existsSync(dir)) continue;
  for (const loc of locales) {
    const filePath = path.join(dir, `${loc}.json`);
    if (!fs.existsSync(filePath)) continue;
    try {
      const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
      let modified = false;
      for (const [key, mapping] of Object.entries(translations)) {
        const val = mapping[loc] || mapping.en || mapping.vi;
        if (data[key] !== val) {
          data[key] = val;
          modified = true;
        }
      }
      if (modified) {
        fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
        console.log(`Updated ${filePath}`);
      }
    } catch (e) {
      console.error(`Error updating ${filePath}:`, e);
    }
  }
}

