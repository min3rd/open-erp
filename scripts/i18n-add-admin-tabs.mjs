const targets = [
  'src/frontend/web/public/i18n',
  'src/frontend/mobile/public/i18n'
];

for (const dir of targets) {
  if (!fs.existsSync(dir)) continue;
  const files = fs.readdirSync(dir).filter(f => f.endsWith('.json'));
  for (const f of files) {
    const lang = f.replace('.json', '');
    const p = path.join(dir, f);
    const content = JSON.parse(fs.readFileSync(p, 'utf8'));

    let added = 0;
    for (const [key, mapping] of Object.entries(translations)) {
      const text = mapping[lang] || mapping['en'] || mapping['vi'];
      if (!content[key]) {
        content[key] = text;
        added++;
      }
    }

    fs.writeFileSync(p, JSON.stringify(content, null, 2) + '\n', 'utf8');
    console.log(`Updated ${p}: added ${added} keys.`);
  }
}

