const locales = ['ar', 'de', 'en', 'es', 'fr', 'id', 'ja', 'ko', 'pt-BR', 'ru', 'th', 'vi', 'zh-CN'];
const targets = [
  'src/frontend/web/public/i18n',
  'src/frontend/mobile/public/i18n',
  'plugins/attendance/src/main/resources/META-INF/resources/i18n'
];

targets.forEach(dir => {
  if (!fs.existsSync(dir)) return;
  locales.forEach(loc => {
    const filePath = path.join(dir, `${loc}.json`);
    if (!fs.existsSync(filePath)) return;
    const content = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    for (const [k, vMap] of Object.entries(translations)) {
      content[k] = vMap[loc] || vMap['en'];
    }
    fs.writeFileSync(filePath, JSON.stringify(content, null, 2) + '\n', 'utf8');
  });
});

console.log('Successfully injected 34 clean translation keys across all 13 locales in Web, Mobile, and Attendance bundle!');

